// Shared plumbing of the accessibility audit: paths, axe injection, the audit recorder and the case-opening helper.
import { createRequire } from 'node:module';
import { existsSync, mkdirSync, readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const app = resolve(dirname(fileURLToPath(import.meta.url)), '..', 'app');
export const pw = createRequire(import.meta.url)(process.env.PW_MODULE || (existsSync('/opt/node-tools/node_modules/playwright') ? '/opt/node-tools/node_modules/playwright' : resolve(app, 'node_modules/playwright')));   // CI: the app's own devDependency
export const axeSource = readFileSync(createRequire(resolve(app, 'package.json')).resolve('axe-core/axe.min.js'), 'utf8');
export const NAV = 'nav[aria-label=Sections] button, .ac-gnav button';
/** `--mode light|dark|auto` and `--contrast standard|enhanced|high`: the viewer's display preference (localStorage `agentcase.display`, docs/THEME.md §6.5), set before the app loads. */
const argv = process.argv.slice(2), arg = (n) => (argv.indexOf(n) < 0 ? '' : argv[argv.indexOf(n) + 1] || '');
export const DISPLAY = arg('--mode') || arg('--contrast') ? JSON.stringify({ mode: arg('--mode') || 'light', contrast: arg('--contrast') || 'standard' }) : '';
/** `--shots <dir>`: a full-page screenshot of every audited state that has a violation (CI uploads the folder as an artifact). At most 60 files. */
const SHOTS = arg('--shots');
if (SHOTS) mkdirSync(SHOTS, { recursive: true });
let shotCount = 0;
const shot = async (page, fixture, section) => {
  if (!SHOTS || shotCount >= 60) return;
  const name = `${String(++shotCount).padStart(2, '0')}-${fixture}-${section}`.replace(/[^\w.-]+/g, '_').slice(0, 120);
  await page.screenshot({ path: resolve(SHOTS, name + '.png'), fullPage: true }).catch(() => {});
};

/** The recorder: `rows` collects { fixture, section, rule, impact, nodes, help, targets }; `audit` runs axe on the page as it is; `note` records a non-axe finding. */
export function recorder() {
  const rows = [], state = { audits: 0 };
  const audit = async (page, fixture, section) => {
    const res = await page.evaluate(async () => {
      // Audit the settled page: finish the running CSS transitions first (a nav button fading out of its active colour, 150 ms, read mid-fade on a
      // slow runner gave a false color-contrast). Infinite animations are left alone; 2 s at most.
      const finite = document.getAnimations().filter((a) => a.effect?.getTiming().iterations !== Infinity);
      await Promise.race([Promise.all(finite.map((a) => a.finished.catch(() => undefined))), new Promise((r) => setTimeout(r, 2000))]);
      const r = await window.axe.run(document, { resultTypes: ['violations'] });
      return r.violations.map((v) => ({ rule: v.id, impact: v.impact, help: v.help, nodes: v.nodes.length, targets: v.nodes.slice(0, 3).map((n) => n.target.join(' ')) }));
    });
    state.audits++;
    for (const v of res) rows.push({ fixture, section, ...v });
    if (res.length) await shot(page, fixture, section);
  };
  const note = (fixture, section, rule, impact, help, target) => rows.push({ fixture, section, rule, impact, nodes: 1, help, targets: [target] });
  return { rows, state, audit, note };
}

/** Open the built app in a fresh page of `ctx`, load fixture `fx` through the Open… input, inject axe. A `pf-*` fixture is a multi-product portfolio file (app/fixtures/portfolios, generated by `npx vite-node scripts/portfolio-fixture.ts`); `pf-example` is the shipped docs/examples/AgentCase_Portfolio_Example.json. */
export async function openCase(ctx, fx) {
  if (DISPLAY) await ctx.addInitScript((p) => { try { localStorage.setItem('agentcase.display', p); } catch { /* storage blocked */ } }, DISPLAY);
  const page = await ctx.newPage();
  await page.goto('file://' + resolve(app, 'dist/index.html')); await page.waitForSelector('.ac-shell');
  await page.setInputFiles('input[type=file]', { name: fx + '.json', mimeType: 'application/json', buffer: readFileSync(fx === 'pf-example' ? resolve(app, '../docs/examples/AgentCase_Portfolio_Example.json') : resolve(app, `fixtures/${fx.startsWith('pf-') ? 'portfolios' : 'cases'}/${fx}.json`)) });
  await page.addScriptTag({ content: axeSource });
  return page;
}

/** Click a navigation entry by its label (sidebar or group bar) and wait until it is the active entry and the section has rendered (no lazy-load placeholder). */
export async function openSection(page, label) {
  const btn = page.locator(NAV).filter({ hasText: new RegExp(`^\\s*${label.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\s*$`) }).first();   // the exact label ("Compliance" is not "Risk & Compliance")
  if (!(await btn.count())) return false;
  if (!(await btn.isVisible())) { const toggle = btn.locator('xpath=ancestor::section').locator('.ac-nav-toggle'); if (await toggle.count()) await toggle.click(); }   // the sidebar groups are an accordion
  // a group header of the sidebar (also a navigation entry) toggles its group: wait for aria-expanded to flip; a section entry: wait until it is active
  const el = await btn.elementHandle(), was = await el.getAttribute('aria-expanded');
  await btn.click();
  await page.waitForFunction(([b, w]) => (w !== null ? b.getAttribute('aria-expanded') !== w : b.classList.contains('is-active'))
    && ![...document.querySelectorAll('main p.ac-muted')].some((p) => p.textContent === 'Loading…'), [el, was], { timeout: 15000 });
  return true;
}
