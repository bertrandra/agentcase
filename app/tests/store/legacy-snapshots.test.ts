import { existsSync, readdirSync, readFileSync, statSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { openCaseText, refitOnOpen } from '@/controllers/openFile';
import { computeCase } from '@/domain';
import { extractLegacyState, parseCaseFile, scanObject } from '@/store/persistence/html/legacy';
import { fromSnapshot, SnapshotError } from '@/store/persistence/snapshot';
import { freshStore } from './helpers';
import { scopeOf } from '@/domain/process';

const IDS = ['golden', 'industry-med', 'ctx-msi'];
const read = (p: string) => readFileSync(p, 'utf8');
const script = (state: string, tail = '); }catch(e){ console.error(e); }') =>
  `<html><body><script data-agentcase-snapshot="1">try{ applySnapshotState(${state}${tail}</script></body></html>`;

describe('legacy HTML snapshots (generated by the v18.11 page: tools/snapshot-fixtures.mjs)', () => {
  it('the committed fixtures stay small', () => IDS.forEach((id) => expect(statSync(`fixtures/snapshots/${id}.html`).size).toBeLessThan(1_000_000)));
  it.each(IDS)('%s: opens, and computeCase equals the oracle figures of the same fixture', (id) => {
    const { kind, raw } = parseCaseFile(read(`fixtures/snapshots/${id}.html`));
    expect(kind).toBe('legacy-html');
    const doc = fromSnapshot(raw), exp = JSON.parse(read(`fixtures/expected/${id}.json`));
    const got = computeCase(doc);
    got.model.yearSav.forEach((v, i) => expect(Math.abs(v - exp.model.yearSav[i])).toBeLessThan(1e-6 * Math.max(1, Math.abs(v))));
    got.model.yearRun.forEach((v, i) => expect(Math.abs(v - exp.model.yearRun[i])).toBeLessThan(1e-6 * Math.max(1, Math.abs(v))));
    expect(got.model.eff).toBeCloseTo(exp.model.eff, 9);
    // the same figures after the open-case re-fit (only the displayed potential moves)
    expect(computeCase(refitOnOpen(doc)).model.yearSav[2]).toBeCloseTo(exp.model.yearSav[2], 4);
  });
  it('the extracted state equals the JSON the legacy page held, and carries the legacy library and metadata', () => {
    const state = JSON.parse(read('fixtures/snapshots/golden.json')) as Record<string, unknown>;
    expect(extractLegacyState(read('fixtures/snapshots/golden.html'))).toEqual(state);
    const doc = fromSnapshot(state);
    expect(doc.appVersion).toBe('v18.12');
    expect((doc.namedSnapshots as { protected?: boolean }[]).some((s) => s.protected)).toBe(true);
  });
  it('opens through the file path with the previous case one undo away', () => {
    const s = freshStore();
    expect(openCaseText(read('fixtures/snapshots/industry-med.html'))).toBe('legacy-html');
    expect(scopeOf(s.getState().doc).selectedNorms.length).toBeGreaterThan(0);
    s.undo();
    expect(scopeOf(s.getState().doc).selectedNorms).toEqual([]);
  });
  it('reads the snapshot baked into the real v18.12 application file', () => {
    const p = '../AgentCase_v18_12_EN.html';
    if (!existsSync(p)) return;
    const doc = fromSnapshot(extractLegacyState(read(p)));
    expect(Object.keys(computeCase(doc).model).length).toBeGreaterThan(10);
  });
});

describe('open-case: fit to scope (legacy applySnapshotState → applyScopeAuto)', () => {
  it('re-fits the potential exactly as the legacy page shows it after opening, for every oracle fixture', () => {
    const fit = JSON.parse(read('fixtures/snapshots/open-fit.json')) as Record<string, string>;
    const ids = readdirSync('fixtures/cases').map((f) => f.replace('.json', ''));
    expect(Object.keys(fit).sort()).toEqual(ids.sort());
    const wrong = ids.filter((id) => refitOnOpen(fromSnapshot(JSON.parse(read(`fixtures/cases/${id}.json`)))).dom.values.autoPotential !== fit[id]);
    expect(wrong).toEqual([]);
  });
  it('is NOT part of the pure conversion: fromSnapshot keeps the stored potential', () => {
    const raw = JSON.parse(read('fixtures/cases/golden.json'));
    raw.dom.values.autoPotential = '60';   // a stored potential that is not the scope's fit (75 for the default scope), fit-to-scope on
    expect(fromSnapshot(raw).dom.values.autoPotential).toBe('60');
    expect(refitOnOpen(fromSnapshot(raw)).dom.values.autoPotential).toBe('75');
  });
  it('leaves a case alone when fit-to-scope is off', () => {
    const raw = JSON.parse(read('fixtures/cases/fit-off-manual.json'));
    expect(refitOnOpen(fromSnapshot(raw)).dom.values.autoPotential).toBe('60');
  });
});

describe('legacy extraction is a parser, not an evaluator', () => {
  const ok = '{"dom":{"values":{},"checked":{}},"s":"a } \\" { b \\\\"}';
  it('handles braces and escaped quotes inside strings', () => {
    expect((extractLegacyState(script(ok)) as { s: string }).s).toBe('a } " { b \\');
    expect(scanObject('{"a":{"b":1}}x', 0)).toBe(13);
  });
  it('rejects anything but the plain restore call', () => {
    for (const bad of [
      script('{"dom":{}}', '); alert(1); }catch(e){}'),     // extra statement after the call
      script('{"dom":{}} + evil()', '); }catch(e){}'),
      script('{"a":1,', ''),                                  // truncated
      script('{a:1}'),                                        // not JSON
      '<html><body><script>var x = 1;</script></body></html>',
      '',
    ]) expect(() => extractLegacyState(bad)).toThrow(SnapshotError);
  });
  it('ignores restore-looking text that is not a script element', () => {
    expect(() => extractLegacyState('<p>try{ applySnapshotState({"dom":{}}); }catch(e){}</p>')).toThrow(SnapshotError);
  });
  it('stacked scripts: the last one wins, as it did when the file ran', () => {
    expect(extractLegacyState(script('{"n":1}') + script('{"n":2}'))).toEqual({ n: 2 });
  });
  it('drops prototype-pollution keys and rejects objects without form inputs', () => {
    const doc = fromSnapshot(extractLegacyState(script('{"dom":{"values":{},"checked":{}},"__proto__":{"polluted":1},"constructor":{"x":1}}')));
    expect(({} as Record<string, unknown>).polluted).toBeUndefined();
    expect(Object.prototype.hasOwnProperty.call(doc, 'constructor')).toBe(false);
    expect(() => fromSnapshot(extractLegacyState(script('{"n":1}')))).toThrow(SnapshotError);
  });
  it('a JSON snapshot file opens too', () => {
    const { kind } = parseCaseFile(read('fixtures/cases/golden.json'));
    expect(kind).toBe('json');
    expect(() => parseCaseFile('{ not json')).toThrow(SnapshotError);
  });
});
