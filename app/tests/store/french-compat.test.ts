import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { exportParamsWorkbook, importParamsWorkbook } from '@/controllers/excelParams';
import { exportSnapshotJson } from '@/controllers/files';
import { openCaseText } from '@/controllers/openFile';
import { addProduct, renameProduct } from '@/controllers/product';
import { addWave, renameWave } from '@/controllers/wave';
import { consolidate, validate, DEFAULT_PRODUCT_NAME, DEFAULT_WAVE_NAME, FRENCH_ALIASES, isDefaultProductName, isDefaultWaveName } from '@/domain/portfolio';
import { appStore } from '@/store/instance';
import { isSingleCase } from '@/store/persistence/portfolioSnapshot';
import { ENV } from '../helpers/excelParams';
import { freshStore } from './helpers';

/**
 * Compatibility with the files of v20.0 (the first multi-product build, French labels): its portfolios carry the French default names "Produit 1" /
 * "Vague 1" (and French user names); the app is English since, writes the English defaults, and must still open and recognise those files.
 */
const pf = () => appStore().getState().portfolio;
const schema = (json: string) => (JSON.parse(json) as { _schema: string })._schema;

describe('English defaults, French defaults still recognised (F22 single-case rule)', () => {
  it('a new case is "Product 1" in "Wave 1"; a new product and a new wave get English default names', () => {
    freshStore();
    expect([pf().products[0]!.name, pf().waves[0]!.name]).toEqual([DEFAULT_PRODUCT_NAME, DEFAULT_WAVE_NAME]);
    addProduct(); addWave();
    expect([pf().products[1]!.name, pf().waves[1]!.name]).toEqual(['Product 2', 'Wave 2']);
  });
  it('both languages are default names; nothing else is', () => {
    expect([DEFAULT_PRODUCT_NAME, ...FRENCH_ALIASES.defaultProductNames].every(isDefaultProductName)).toBe(true);
    expect([DEFAULT_WAVE_NAME, ...FRENCH_ALIASES.defaultWaveNames].every(isDefaultWaveName)).toBe(true);
    expect(isDefaultProductName('Produit 2') || isDefaultWaveName('Vague 2') || isDefaultProductName('Payroll')).toBe(false);
  });
  it('a single product named "Produit 1" in "Vague 1" (v20.0 default) is still a plain single case: saved as the v1 snapshot', () => {
    freshStore();
    renameProduct(pf().products[0]!.id, 'Produit 1'); renameWave(pf().waves[0]!.id, 'Vague 1');
    expect(isSingleCase(pf())).toBe(true);
    expect(schema(exportSnapshotJson().json)).toBe('agentcase.snapshot.v1');
  });
  it('a renamed single product keeps the portfolio format, French or English', () => {
    for (const name of ['Paie', 'Payroll']) {
      freshStore();
      renameProduct(pf().products[0]!.id, name);
      expect(isSingleCase(pf())).toBe(false);
    }
  });
});

/** A v20.0 file: a portfolio with French names written by the real export, opened again by the current build. */
function frenchPortfolio(): void {
  freshStore();
  renameProduct(pf().products[0]!.id, 'Produit 1'); renameWave(pf().waves[0]!.id, 'Vague 1');
  const b = addProduct('Paie', pf().waves[0]!.id)!, w2 = addWave('Vague 2', 6)!;
  addProduct('Facturation', w2); renameProduct(b, 'Paie');
}
const names = () => ({ products: pf().products.map((p) => p.name), waves: pf().waves.map((w) => w.name) });
const FRENCH = { products: ['Produit 1', 'Paie', 'Facturation'], waves: ['Vague 1', 'Vague 2'] };

describe('a v20.0 portfolio with French names still opens and round-trips', () => {
  it('JSON: the names, waves and products survive export and open', () => {
    frenchPortfolio();
    expect(names()).toEqual(FRENCH);
    const json = exportSnapshotJson().json;
    expect(schema(json)).toBe('agentcase.portfolio.v1');
    freshStore(); openCaseText(json);
    expect(names()).toEqual(FRENCH);
  });
  it('Excel parameters workbook: the sheets are the same in both languages, French user names survive', async () => {
    frenchPortfolio();
    const bytes = await (await exportParamsWorkbook('all', ENV)).blob.arrayBuffer();
    freshStore();
    await importParamsWorkbook({ name: 'pf.xlsx', size: bytes.byteLength, arrayBuffer: async () => bytes }, ENV);
    expect(names()).toEqual(FRENCH);
  });
});

describe('the real v20.0 file (French labels, generated by that build)', () => {
  it('opens through the real open path, validates, consolidates, and keeps its French names', () => {
    freshStore(); openCaseText(readFileSync('tests/store/data/pf-v20-french.json', 'utf8'));
    expect(validate(pf()).errors).toEqual([]);
    expect(names()).toEqual({ products: ['Produit 1', 'Paie', 'Facturation', 'Archivage (hors vague)'], waves: ['Vague 1', 'Vague 2'] });
    expect(consolidate(pf()).products).toHaveLength(3);
  });
  it('saving it again keeps the names (nothing is renamed behind the user\'s back) and the portfolio format', () => {
    freshStore(); openCaseText(readFileSync('tests/store/data/pf-v20-french.json', 'utf8'));
    const json = exportSnapshotJson().json;
    expect(schema(json)).toBe('agentcase.portfolio.v1');
    freshStore(); openCaseText(json);
    expect(pf().products.map((p) => p.name)).toContain('Archivage (hors vague)');
  });
});
